constexpr std::uint64_t max_xlsx_data_rows = 1'048'575;

std::uint64_t combination_count(size_t n, size_t k)
{
    if (n < k)
        return 0;

    k                    = std::min(k, n - k);
    std::uint64_t result = 1;
    for (size_t i = 1; i <= k; ++i)
        result = result * static_cast<std::uint64_t>(n - k + i) / static_cast<std::uint64_t>(i);
    return result;
}

wxString from_utf8(const std::string& value) { return wxString::FromUTF8(value.c_str()); }

std::string to_utf8(const wxString& value) { return value.ToUTF8().data(); }

