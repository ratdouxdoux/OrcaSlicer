void require(bool condition, const std::string& message)
{
    if (!condition)
        throw std::runtime_error(message);
}

int integer(const Json& value, int minimum, int maximum)
{
    require(value.is_number_integer(), "expected an integer");
    // Check before narrowing: get<int>() alone would silently wrap large IDs.
    require(value >= minimum && value <= maximum, "integer outside the supported range");
    return value.get<int>();
}

float number(const Json& value, float minimum, float maximum)
{
    require(value.is_number(), "expected a number");
    const double result = value.get<double>();
    require(std::isfinite(result) && result >= minimum && result <= maximum, "number outside the supported range");
    return static_cast<float>(result);
}

unsigned int filament(const Json& value, size_t physical_count)
{
    return unsigned(integer(value, 1, int(std::min(physical_count, MixedFilamentManager::kMaxPhysicalFilaments))));
}

std::vector<float> fractions(const Json& value, size_t expected_count)
{
    require(value.is_array() && value.size() == expected_count, "incorrect gradient array length");
    std::vector<float> result;
    for (const auto& item : value)
        result.push_back(number(item, 0.f, 1.f));
    return result;
}

MixedFilamentDefinition read_recipe(const Json& recipe, size_t physical_count)
{
    require(recipe.is_object(), "expected a recipe object");
    MixedFilamentDefinition result;
    const auto              id     = recipe.at("id").get<std::string>();
    const auto              parsed = std::from_chars(id.data(), id.data() + id.size(), result.identity.stable_id);
    require(parsed.ec == std::errc() && parsed.ptr == id.data() + id.size() && result.identity.stable_id != 0,
            "id must be a nonzero unsigned 64-bit decimal string");

    const auto& components = recipe.at("components");
    require(components.is_array() && components.size() >= 2 && components.size() <= MixedFilamentManager::kMaxPhysicalFilaments,
            "a recipe needs two or more physical components");
    std::set<unsigned int> component_ids;
    int                    total = 0;
    for (const auto& component : components) {
        const auto id = filament(component.at("filament"), physical_count);
        require(component_ids.insert(id).second, "duplicate component filament");
        const int percent = integer(component.at("percent"), 0, 100);
        total += percent;
        result.recipe.blend.components.push_back({{id}, percent});
    }
    require(total == 100, "component percentages must sum to 100");

    const auto distribution = recipe.at("distribution").get<std::string>();
    require(distribution == "simple" || distribution == "layer_cycle", "unsupported distribution");
    result.behavior.distribution = distribution == "simple" ? MixedFilamentDistributionMode::Simple :
                                                              MixedFilamentDistributionMode::LayerCycle;
    const auto state             = recipe.value("state", std::string("active"));
    require(state == "active" || state == "disabled" || state == "deleted", "unsupported recipe state");
    result.visibility.enabled    = state == "active";
    result.visibility.tombstoned = state == "deleted";
    const auto origin            = recipe.value("origin", std::string("manual"));
    require(origin == "manual" || origin == "generated" || origin == "customized_generated", "unsupported recipe origin");
    result.source.kind        = origin == "generated" ? MixedFilamentSourceKind::AutoGenerated : MixedFilamentSourceKind::Custom;
    result.source.origin_auto = recipe.value("origin_auto", origin != "manual");
    if (recipe.contains("ui_mode"))
        result.presentation.ui_mode = integer(recipe.at("ui_mode"), -1, 3);
    if (recipe.contains("pair_percent_b"))
        result.behavior.layer_cadence.legacy_mix_b_percent =
            MixedFilamentLayerCadence::LegacyMixPercent{integer(recipe.at("pair_percent_b"), 0, 100),
                                                        result.recipe.blend.primary_pair_or().component_b_percent};
    if (recipe.contains("local_z"))
        result.behavior.local_z.max_sublayers = integer(recipe.at("local_z").at("max_sublayers"), 0, std::numeric_limits<int>::max());
    if (recipe.contains("surface_bias")) {
        const auto& bias                                   = recipe.at("surface_bias");
        result.behavior.surface_bias.component_a_offset_mm = number(bias.at("a_mm"), -2.f, 2.f);
        result.behavior.surface_bias.component_b_offset_mm = number(bias.at("b_mm"), -2.f, 2.f);
    }
    if (recipe.contains("pattern")) {
        const auto& groups = recipe.at("pattern");
        require(groups.is_array() && !groups.empty(), "pattern needs at least one group");
        MixedFilamentManualPattern pattern;
        for (const auto& group : groups) {
            require(group.is_array() && !group.empty(), "pattern groups cannot be empty");
            std::vector<MixedFilamentPhysicalRef> refs;
            for (const auto& ref : group)
                refs.push_back({filament(ref, physical_count)});
            pattern.groups.push_back(std::move(refs));
        }
        result.recipe.kind           = MixedFilamentRecipeKind::ManualPattern;
        result.recipe.manual_pattern = std::move(pattern);
    }
    if (recipe.contains("gradient")) {
        const auto& gradient     = recipe.at("gradient");
        auto&       target       = result.behavior.gradient;
        target.enabled           = true;
        target.component_a_start = number(gradient.at("start"), 0.f, 1.f);
        target.component_a_end   = number(gradient.at("end"), 0.f, 1.f);
        require(std::abs(target.component_a_start - target.component_a_end) >= MixedFilamentLegacyRow::k_min_gradient_difference,
                "gradient start and end must differ by at least 0.05");
        const auto& order = gradient.at("order");
        require(order.is_array() && order.size() == component_ids.size(), "gradient order must include every component once");
        std::set<unsigned int> seen;
        for (const auto& ref : order) {
            const auto id = filament(ref, physical_count);
            require(component_ids.count(id) != 0 && seen.insert(id).second, "invalid gradient component order");
            target.color_order.push_back(id);
        }
        if (gradient.contains("stops")) {
            target.stop_positions = fractions(gradient.at("stops"), 2 * order.size() - 1);
            require(target.stop_positions.front() == 0.f && target.stop_positions.back() == 1.f &&
                        std::is_sorted(target.stop_positions.begin(), target.stop_positions.end()),
                    "invalid gradient stops");
        }
        if (gradient.contains("solid_widths"))
            target.solid_widths = fractions(gradient.at("solid_widths"), order.size());
    }
    return result;
}

Json write_recipe(const MixedFilamentDefinition& definition)
{
    const auto& behavior = definition.behavior;
    require(behavior.distribution != MixedFilamentDistributionMode::RetiredSameLayer, "retired distribution must be migrated first");
    Json recipe = {{"id", std::to_string(definition.identity.stable_id)},
                   {"distribution", behavior.distribution == MixedFilamentDistributionMode::Simple ? "simple" : "layer_cycle"},
                   {"components", Json::array()}};
    for (const auto& component : definition.recipe.blend.components)
        recipe["components"].push_back({{"filament", component.filament.id}, {"percent", component.percent}});
    if (definition.visibility.tombstoned)
        recipe["state"] = "deleted";
    else if (!definition.visibility.enabled)
        recipe["state"] = "disabled";
    if (definition.source.kind == MixedFilamentSourceKind::AutoGenerated) {
        recipe["origin"] = "generated";
        if (!definition.source.origin_auto)
            recipe["origin_auto"] = false;
    } else if (definition.source.origin_auto)
        recipe["origin"] = "customized_generated";
    if (definition.presentation.ui_mode >= 0)
        recipe["ui_mode"] = definition.presentation.ui_mode;
    const auto& pair_percent = behavior.layer_cadence.legacy_mix_b_percent;
    const int   percent_b    = definition.recipe.blend.primary_pair_or().component_b_percent;
    if (pair_percent && pair_percent->source_component_b_percent == percent_b && pair_percent->value != percent_b)
        recipe["pair_percent_b"] = pair_percent->value;
    if (behavior.local_z.max_sublayers != 0)
        recipe["local_z"] = {{"max_sublayers", behavior.local_z.max_sublayers}};
    if (behavior.surface_bias.component_a_offset_mm != 0.f || behavior.surface_bias.component_b_offset_mm != 0.f)
        recipe["surface_bias"] = {{"a_mm", behavior.surface_bias.component_a_offset_mm},
                                  {"b_mm", behavior.surface_bias.component_b_offset_mm}};
    if (definition.recipe.manual_pattern) {
        recipe["pattern"] = Json::array();
        for (const auto& group : definition.recipe.manual_pattern->groups) {
            Json refs = Json::array();
            for (const auto& ref : group)
                refs.push_back(ref.id);
            recipe["pattern"].push_back(std::move(refs));
        }
    }
    if (behavior.gradient.enabled) {
        const auto& gradient = behavior.gradient;
        recipe["gradient"]   = {{"order", gradient.color_order.empty() ? definition.recipe.blend.component_ids() : gradient.color_order},
                                {"start", gradient.component_a_start},
                                {"end", gradient.component_a_end}};
        if (!gradient.stop_positions.empty())
            recipe["gradient"]["stops"] = gradient.stop_positions;
        if (!gradient.solid_widths.empty())
            recipe["gradient"]["solid_widths"] = gradient.solid_widths;
    }
    return recipe;
}
