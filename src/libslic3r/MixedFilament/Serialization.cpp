std::vector<MixedFilamentDefinition> deserialize_mixed_filaments_json(const std::string& json, size_t physical_count)
{
    try {
        const auto document = Json::parse(json);
        require(document.is_object(), "expected an object");
        require(integer(document.at("version"), 1, std::numeric_limits<int>::max()) == 1, "unsupported format version");
        const auto& recipes = document.at("recipes");
        require(recipes.is_array(), "recipes must be an array");
        std::vector<MixedFilamentDefinition> definitions;
        std::set<uint64_t>                   ids;
        for (const auto& recipe : recipes) {
            try {
                auto definition = read_recipe(recipe, physical_count);
                require(ids.insert(definition.identity.stable_id).second, "duplicate recipe id");
                definitions.push_back(std::move(definition));
            } catch (const std::exception& e) {
                throw std::runtime_error("recipe " + std::to_string(definitions.size() + 1) + ": " + e.what());
            }
        }
        return definitions;
    } catch (const std::exception& e) {
        throw std::runtime_error(std::string(MIXED_FILAMENTS_3MF_PATH) + ": " + e.what());
    }
}

std::string serialize_mixed_filaments_json(const std::vector<MixedFilamentDefinition>& definitions, size_t physical_count)
{
    Json document = {{"version", 1}, {"recipes", Json::array()}};
    for (const auto& definition : definitions)
        document["recipes"].push_back(write_recipe(definition));
    const auto text = document.dump(2) + '\n';
    // Apply the same validation on write: never create an archive we cannot read.
    deserialize_mixed_filaments_json(text, physical_count);
    return text;
}

std::vector<MixedFilamentDefinition> mixed_filaments_from_project_config(const DynamicPrintConfig& config, size_t physical_count)
{
    const auto* rows = config.option<ConfigOptionString>("mixed_filament_definitions");
    if (rows == nullptr || rows->value.empty())
        return {};
    MixedFilamentManager manager;
    manager.load_custom_entries(rows->value, std::vector<std::string>(physical_count, "#FFFFFF"), MixedFilamentManager::LoadMode::Exact);
    auto definitions = manager.mixed_filament_definitions();
    // Legacy parsing is permissive during old-project loading. Saving must not
    // silently drop rows, since that would shift all subsequent virtual tools.
    std::istringstream stream(rows->value);
    std::string        row;
    size_t             count = 0;
    while (std::getline(stream, row, ';'))
        count += !row.empty();
    require(definitions.size() == count, "Cannot save mixed filaments: invalid legacy recipe or physical filament reference");
    return definitions;
}

std::string mixed_filaments_to_legacy(const std::vector<MixedFilamentDefinition>& definitions)
{
    MixedFilamentManager manager;
    manager.set_mixed_filament_definitions(definitions, {});
    return manager.serialize_custom_entries();
}

